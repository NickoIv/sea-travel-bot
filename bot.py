# ─── Рассылка ────────────────────────────────────────────────────────────────

async def send_daily_digest(bot):
    """Общее тело ежедневной рассылки — вызывается либо из JobQueue (локальный
    polling-режим), либо из HTTP /cron/daily, который дёргает Cloud Scheduler
    (Cloud Run-режим, где нет собственного постоянно работающего планировщика)."""
    data = await asyncio.to_thread(load_data)
    if not data["subscribers"]: return
    news = await asyncio.to_thread(fetch_news)
    if not news: return
    text = fmt_digest(news)
    await asyncio.to_thread(mark_sent_many, [n["hash"] for n in news])
    for uid in data["subscribers"]:
        try:
            await bot.send_message(uid, text, parse_mode="HTML", disable_web_page_preview=True)
            await asyncio.sleep(0.05)
        except Exception as e:
            log.warning(f"Send error {uid}: {e}")

async def send_daily_job(ctx: ContextTypes.DEFAULT_TYPE):
    """Обёртка под сигнатуру callback'а JobQueue (используется только в
    локальном polling-режиме)."""
    await send_daily_digest(ctx.bot)

# ─── Inline-поиск отелей (@bot_name название — из любого чата) ────────────────
# Настоящие "подсказки по мере набора" в Telegram работают только через
# inline-режим, а не через обычные reply-кнопки. В отличие от остального
# бота, inline-запрос не привязан к состоянию конкретного чата (никакой
# текущей страны/города) — поэтому ищем сразу по всем городам.

INLINE_SEARCH_LIMIT = 20

async def inline_hotel_search(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    query = (update.inline_query.query or "").strip()
    if len(query) < 2:
        await update.inline_query.answer([], cache_time=5, is_personal=True)
        return
    q = query.lower()

    def _search_all_cities():
        # Только то, что уже закэшировано ранее обычным поиском в чате —
        # никаких новых сетевых запросов здесь: у inline-режима свой,
        # значительно более короткий бюджет времени на ответ в Telegram.
        seen, matches = set(), []
        for code, cities in CITIES.items():
            for c in cities:
                curated_raw = CURATED.get((code, c["key"]), {}).get("hotels", [])
                cached_pool = _city_hotel_cache.get((code, c["key"])) or []
                for h in [_curated_hotel_to_item(x) for x in curated_raw] + cached_pool:
                    name_lower = h["name"].lower()
                    if q in name_lower and name_lower not in seen:
                        seen.add(name_lower)
                        matches.append((h, code, c))
        matches.sort(key=lambda m: _hotel_rank(m[0]), reverse=True)
        return matches[:INLINE_SEARCH_LIMIT]

    matches = _search_all_cities()

    results = []
    for h, code, c in matches:
        city_en = c.get("en", c["name"])
        line = fmt_hotel_line(1, h, city_en)
        line = line.split(". ", 1)[1] if line.startswith("1. ") else line
        _, country_name = COUNTRIES.get(code, ("", ""))
        stars = _stars_str(h.get("stars")).strip()
        desc = f"{c['name']}, {country_name}" + (f" · {stars}" if stars else "")
        results.append(InlineQueryResultArticle(
            id=hashlib.md5(f"{code}{c['key']}{h['name']}".encode()).hexdigest(),
            title=h["name"],
            description=desc,
            input_message_content=InputTextMessageContent(line, parse_mode="HTML", disable_web_page_preview=True),
        ))
    await update.inline_query.answer(results, cache_time=30, is_personal=True)

# ─── Запуск ──────────────────────────────────────────────────────────────────
# Локально (WEBHOOK_MODE не задан и платформа не прописала свою переменную)
# бот работает как раньше через run_polling + JobQueue. На хостинге вроде
# Render — через вебхук на HTTP-сервере aiohttp, а ежедневную рассылку
# дёргает внешний бесплатный крон (cron-job.org) HTTP-запросом на
# /cron/daily — свой процесс-планировщик в контейнере, который может
# "уснуть" при простое (бесплатный тариф Render), для этого не подходит.

def build_app() -> Application:
    app = Application.builder().token(BOT_TOKEN).build()
    app.add_handler(CommandHandler("start", cmd_start))
    app.add_handler(CommandHandler("help", cmd_help))
    app.add_handler(CommandHandler("subscribe", cmd_subscribe))
    app.add_handler(CommandHandler("unsubscribe", cmd_unsubscribe))
    app.add_handler(CommandHandler("status", cmd_status))
    app.add_handler(InlineQueryHandler(inline_hotel_search))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_text))
    return app

def run_polling_mode():
    app = build_app()
    # JobQueue управляется тем же event loop, что и run_polling — в отличие от
    # отдельного AsyncIOScheduler, запущенного до старта polling-цикла, задания
    # здесь гарантированно срабатывают по расписанию.
    app.job_queue.run_daily(
        send_daily_job,
        time=dtime(hour=5, minute=0, tzinfo=timezone.utc),  # 10:00 Алматы
    )
    log.info("🌴 SEA Travel News Bot запущен (polling)!")
    app.run_polling(drop_pending_updates=True)

def run_webhook_mode():
    from aiohttp import web

    app = build_app()
    webhook_path = f"/webhook/{BOT_TOKEN}"

    async def handle_webhook(request: web.Request):
        data = await request.json()
        update = Update.de_json(data, app.bot)
        await app.update_queue.put(update)
        return web.Response(status=200)

    async def handle_cron(request: web.Request):
        if DAILY_CRON_SECRET and request.headers.get("X-Cron-Secret") != DAILY_CRON_SECRET:
            return web.Response(status=403, text="forbidden")
        # Сборка новостей + перевод каждой через Google Translate может занять
        # больше 30 сек — это дольше таймаута большинства внешних крон-сервисов
        # (в т.ч. cron-job.org). Поэтому отвечаем сразу, а рассылку запускаем
        # фоновой задачей — cron просто "будит" эндпоинт, не дожидаясь результата.
        asyncio.create_task(send_daily_digest(app.bot))
        return web.Response(status=200, text="started")

    async def handle_health(request: web.Request):
        return web.Response(status=200, text="ok")

    async def run():
        await app.initialize()
        await app.start()
        web_app = web.Application()
        web_app.add_routes([
            web.post(webhook_path, handle_webhook),
            web.post("/cron/daily", handle_cron),
            web.get("/", handle_health),
        ])
        runner = web.AppRunner(web_app)
        await runner.setup()
        site = web.TCPSite(runner, "0.0.0.0", PORT)
        await site.start()
        log.info(f"🌴 SEA Travel News Bot запущен (webhook, порт {PORT})!")
        await asyncio.Event().wait()  # держим процесс живым

    asyncio.run(run())

def main():
    if not BOT_TOKEN:
        print("❌ Укажи BOT_TOKEN!")
        return
    if WEBHOOK_MODE:
        run_webhook_mode()
    else:
        run_polling_mode()

if __name__ == "__main__":
    main()
