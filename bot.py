async def send_hotels_page(ctx: ContextTypes.DEFAULT_TYPE, chat_id: int, code: str, city_key: str,
                            city: dict, hotels: list[dict], offset: int, filtered: bool = False):
    country_name = COUNTRIES.get(code, ("", ""))[1]
    if not hotels:
        await ctx.bot.send_message(chat_id, fmt_hotels_header(city, country_name, 0),
                                    parse_mode="HTML", reply_markup=hotels_kb(0, 0, filtered))
        return
    if offset == 0:
        city_photo = await asyncio.to_thread(get_city_photo, city)
        if city_photo:
            try:
                await ctx.bot.send_photo(chat_id, photo=city_photo, caption=f"{city['icon']} {city['name']}, {country_name}")
            except Exception as e:
                log.warning(f"Send city photo failed: {e}")
    page = hotels[offset:offset + HOTEL_PAGE_SIZE]
    city_en = city.get("en", city["name"])
    await asyncio.to_thread(_translate_page_names, page)
    await asyncio.to_thread(_resolve_page_photos, page, city_en)
    header = fmt_hotels_header(city, country_name, len(hotels))
    await ctx.bot.send_message(chat_id, header, parse_mode="HTML", reply_markup=hotels_kb(offset, len(hotels), filtered))
    text_lines = []
    for j, h in enumerate(page):
        i = offset + j + 1
        line = fmt_hotel_line(i, h, city_en)
        photo = h.get("photo_bytes")
        if photo:
            try:
                await ctx.bot.send_photo(chat_id, photo=photo, caption=line, parse_mode="HTML")
                continue
            except Exception as e:
                log.warning(f"Send hotel photo failed: {e}")
        text_lines.append(line)
    if text_lines:
        await ctx.bot.send_message(chat_id, "\n".join(text_lines), parse_mode="HTML", disable_web_page_preview=True)

# ─── Достопримечательности/кафе: отправка страницы ────────────────────────────

async def send_poi_page(ctx: ContextTypes.DEFAULT_TYPE, chat_id: int, kind: str, code: str, city_key: str,
                         city: dict, items: list[dict], offset: int):
    cfg = POI_KINDS[kind]
    country_name = COUNTRIES.get(code, ("", ""))[1]
    if not items:
        await ctx.bot.send_message(chat_id, fmt_poi_header(kind, city, country_name, 0),
                                    parse_mode="HTML", reply_markup=poi_kb(0, 0))
        return
    if offset == 0:
        city_photo = await asyncio.to_thread(get_city_photo, city)
        if city_photo:
            try:
                await ctx.bot.send_photo(chat_id, photo=city_photo, caption=f"{city['icon']} {city['name']}, {country_name}")
            except Exception as e:
                log.warning(f"Send city photo failed: {e}")
    page = items[offset:offset + POI_PAGE_SIZE]
    city_en = city.get("en", city["name"])
    await asyncio.to_thread(_translate_page_names, page)
    if cfg["photos"]:
        await asyncio.to_thread(_resolve_page_photos, page, city_en)
    header = fmt_poi_header(kind, city, country_name, len(items))
    await ctx.bot.send_message(chat_id, header, parse_mode="HTML", reply_markup=poi_kb(offset, len(items)))
    text_lines = []
    last_cat = None
    for j, it in enumerate(page):
        i = offset + j + 1
        cat = it.get("cat_key")
        if cat != last_cat:
            last_cat = cat
            prefix = "\n" if text_lines else ""
            text_lines.append(f"{prefix}{it.get('group_icon','📍')} <b>{it.get('group_label','')}</b>")
        line = fmt_poi_line(i, it, city_en)
        photo = it.get("photo_bytes")
        if photo:
            try:
                await ctx.bot.send_photo(chat_id, photo=photo, caption=line, parse_mode="HTML")
                continue
            except Exception as e:
                log.warning(f"Send poi photo failed: {e}")
        text_lines.append(line)
    if text_lines:
        await ctx.bot.send_message(chat_id, "\n".join(text_lines), parse_mode="HTML", disable_web_page_preview=True)

# ─── Кнопки Reply ─────────────────────────────────────────────────────────────

async def handle_text(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    text = update.message.text
    chat_id = update.effective_chat.id
    state = get_state(chat_id)

    # ── Главное меню (доступно с любого экрана — не жать "Назад" по многу раз) ──
    if text == "🏠 Главное меню":
        set_state(chat_id, screen="root", country=None, city=None)
        await update.message.reply_text("Главное меню 👇", reply_markup=main_kb())
        return

    if text == "📍 Страны":
        set_state(chat_id, screen="countries", country=None, city=None)
        await update.message.reply_text("🌍 Выбери страну:", reply_markup=countries_kb())
        return

    if text == "🌴 Все новости":
        msg = await update.message.reply_text("⏳ Собираю и перевожу новости...")
        news = await asyncio.to_thread(fetch_news)
        mark_sent_many([n["hash"] for n in news])
        await msg.edit_text(fmt_digest(news), parse_mode="HTML", disable_web_page_preview=True)
        return

    if text == "💱 Курс валют":
        await update.message.reply_text(get_rates(), parse_mode="HTML", reply_markup=rates_kb())
        return

    if text == "🧮 Конвертер валют":
        set_state(chat_id, screen="converter_pick")
        await update.message.reply_text(
            "Выбери валюту, из которой считаем — переведу в тенге:",
            reply_markup=currency_picker_kb(),
        )
        return

    if state.get("screen") == "converter_pick" and text in CURRENCY_LABEL_TO_CODE:
        code = CURRENCY_LABEL_TO_CODE[text]
        flag, code_str, name = CURRENCIES[code]
        set_state(chat_id, screen="converter_amount", converter_currency=code)
        await update.message.reply_text(
            f"{flag} Введи сумму в {code_str} ({name}) — посчитаю в тенге:",
            reply_markup=converter_amount_kb(),
        )
        return

    if text == "🔁 Сменить валюту" and state.get("screen") == "converter_amount":
        set_state(chat_id, screen="converter_pick")
        await update.message.reply_text("Выбери валюту, из которой считаем:", reply_markup=currency_picker_kb())
        return

    if (state.get("screen") == "converter_amount" and state.get("converter_currency")
            and text not in ("⬅️ Назад", "🏠 Главное меню", "🔁 Сменить валюту")):
        code = state["converter_currency"]
        flag, code_str, name = CURRENCIES[code]
        amount = _parse_amount(text)
        if amount is None:
            await update.message.reply_text(
                f"Не понял сумму — введи просто число, например 500000",
                reply_markup=converter_amount_kb(),
            )
            return
        kzt_amount = await asyncio.to_thread(convert_to_kzt, amount, code)
        if kzt_amount is None:
            await update.message.reply_text("Курс временно недоступен, попробуй чуть позже.", reply_markup=converter_amount_kb())
            return
        await update.message.reply_text(
            f"{flag} {amount:,.0f} {code_str} ≈ <b>{kzt_amount:,.0f} KZT</b>",
            parse_mode="HTML", reply_markup=converter_amount_kb(),
        )
        return

    if text == "🔔 Рассылка новостей":
        set_state(chat_id, screen="news_settings")
        await update.message.reply_text(
            fmt_news_settings(is_subscribed(chat_id)),
            parse_mode="HTML", reply_markup=news_settings_kb(is_subscribed(chat_id)),
        )
        return

    if text == "🔔 Подписаться" and state.get("screen") == "news_settings":
        add_subscriber(chat_id)
        await update.message.reply_text(
            fmt_news_settings(True), parse_mode="HTML", reply_markup=news_settings_kb(True),
        )
        return

    if text == "🔕 Отписаться" and state.get("screen") == "news_settings":
        remove_subscriber(chat_id)
        await update.message.reply_text(
            fmt_news_settings(False), parse_mode="HTML", reply_markup=news_settings_kb(False),
        )
        return

    if text == "📖 Показать сейчас" and state.get("screen") == "news_settings":
        msg = await update.message.reply_text("⏳ Собираю и перевожу новости...")
        news = await asyncio.to_thread(fetch_news)
        mark_sent_many([n["hash"] for n in news])
        await msg.edit_text(fmt_digest(news), parse_mode="HTML", disable_web_page_preview=True)
        return

    if text == "ℹ️ О боте":
        await update.message.reply_text(
            "🌴 <b>SEA Travel News Bot</b>\n\n"
            "Новости, погода, визы, отели, достопримечательности, кафе и курс валют\n"
            "по Вьетнаму, Индонезии (Бали), Сингапуру, Египту и Хайнаню (Китай).\n\n"
            "📅 Дайджест ежедневно в 10:00 по Алматы\n"
            "🇷🇺 Новости переводятся на русский\n🆓 Без рекламы\n\n"
            "👤 Автор: Ивашикин Николай",
            parse_mode="HTML", reply_markup=main_kb(),
        )
        return

    # ── Выбор страны ──
    if text in COUNTRY_LABEL_TO_CODE:
        code = COUNTRY_LABEL_TO_CODE[text]
        cities = CITIES.get(code, [])
        if len(cities) == 1:
            city = cities[0]
            set_state(chat_id, screen="city", country=code, city=city["key"])
            await update.message.reply_text(await asyncio.to_thread(fmt_city_card, code, city), parse_mode="HTML", reply_markup=city_kb())
        else:
            set_state(chat_id, screen="cities", country=code, city=None)
            flag, name = COUNTRIES[code]
            await update.message.reply_text(
                f"{flag} <b>{name}</b>\n🕐 Сейчас там: {local_time_str(code)}\n\nВыбери город:",
                parse_mode="HTML", reply_markup=cities_kb(code),
            )
        return

    # ── Выбор города ──
    if text in CITY_LABEL_TO_KEY:
        code, city_key = CITY_LABEL_TO_KEY[text]
        city = find_city(code, city_key)
        set_state(chat_id, screen="city", country=code, city=city_key)
        await update.message.reply_text(await asyncio.to_thread(fmt_city_card, code, city), parse_mode="HTML", reply_markup=city_kb())
        return

    # ── Новости / виза / рейсы (уровень страны, доступны из cities и city) ──
    if text == "📰 Новости страны" and state.get("country"):
        code = state["country"]
        name = COUNTRIES.get(code, ("", ""))[1]
        msg = await update.message.reply_text("⏳ Собираю новости...")
        news = await asyncio.to_thread(fetch_news, country=code)
        mark_sent_many([n["hash"] for n in news])
        await msg.edit_text(fmt_digest(news, title=f"Новости — {name}"), parse_mode="HTML", disable_web_page_preview=True)
        return

    if text == "🗺️ Виза" and state.get("country"):
        await update.message.reply_text(
            VISA_INFO.get(state["country"], "Информация недоступна"),
            parse_mode="HTML", reply_markup=current_kb(state), disable_web_page_preview=True,
        )
        return

    if text == "✈️ Рейсы из Алматы":
        await update.message.reply_text(FLIGHTS_INFO, parse_mode="HTML", reply_markup=current_kb(state))
        return

    if text == "📶 eSIM" and state.get("country"):
        await update.message.reply_text(
            fmt_esim_info(state["country"]),
            parse_mode="HTML", reply_markup=current_kb(state),
        )
        return

    if text == "🧭 Полезное туристу" and state.get("country"):
        set_state(chat_id, screen="practical")
        await update.message.reply_text(
            "🧭 <b>Полезное для самостоятельного туриста</b> — выбери раздел:",
            parse_mode="HTML", reply_markup=practical_kb(),
        )
        return

    if text == "🆘 Экстренная помощь" and state.get("country"):
        await update.message.reply_text(fmt_safety_info(state["country"]), parse_mode="HTML", reply_markup=practical_kb())
        return

    if text == "🚕 Транспорт" and state.get("country"):
        await update.message.reply_text(fmt_transport_info(state["country"]), parse_mode="HTML", reply_markup=practical_kb())
        return

    if text == "💵 Деньги на месте" and state.get("country"):
        await update.message.reply_text(fmt_money_info(state["country"]), parse_mode="HTML", reply_markup=practical_kb())
        return

    # ── Отели ──
    if text == "🏨 Отели" and state.get("country") and state.get("city"):
        code, city_key = state["country"], state["city"]
        city = find_city(code, city_key)
        # Кураторские данные всегда под рукой без похода в сеть — сразу ведём
        # в меню поиска/фильтров, а не вываливаем список: с поиском по
        # названию и фильтрами по звёздам/району отдельный экран-каталог
        # больше не нужен.
        hotels = await asyncio.to_thread(shuffle_city_hotels, code, city_key)
        set_state(chat_id, screen="hotels", hotel_offset=0, hotel_filter=None)
        country_name = COUNTRIES.get(code, ("", ""))[1]
        await update.message.reply_text(
            fmt_hotels_header(city, country_name, len(hotels)),
            parse_mode="HTML", reply_markup=hotels_kb(0, len(hotels)),
        )
        return

    if text.startswith("▶️ Ещё") and state.get("screen") == "hotels":
        code, city_key = state.get("country"), state.get("city")
        city = find_city(code, city_key)
        hotels = state.get("hotel_filter") or _shown_hotels_cache.get((code, city_key)) or []
